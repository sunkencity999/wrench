"""Clickable desktop notifications, and `wrench show`.

The problem this solves: on macOS, a notification sent with
``osascript -e 'display notification …'`` belongs to Script Editor, so
clicking it (or its "Show" button) opens Script Editor's file dialog — not
anything about the alert.

A notification is opened by the app that posted it. So wrench builds a tiny
helper app of its own (an AppleScript applet, compiled once with the
``osacompile`` that ships with macOS) and posts through that:

* wrench writes the title and body to ``<data dir>/notifier/`` and launches
  the helper, which posts the notification under its own name;
* when the notification is clicked, macOS launches the helper again; finding
  nothing waiting to be posted, it runs ``wrench show --from-toast``;
* ``wrench show`` makes sure the dashboard is running (starting it in the
  background on this machine if it is not) and opens the browser at the
  notification that was clicked.

The first notification from the helper makes macOS ask once whether "wrench"
may send notifications. If the helper cannot be built or launched, the old
``osascript`` path is used, so an alert is never lost to this feature.

The helper holds no logic and no secrets: text travels in files, never in
script source, so a finding's wording cannot become code.
"""

from __future__ import annotations

import hashlib
import json
import os
import platform
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

BUNDLE_ID = "io.github.sunkencity999.wrench.notifier"
APP_NAME = "wrench.app"
DIR_NAME = "notifier"
PENDING_MAX_AGE_S = 60
WEB_PID = "web.pid"
WEB_LOG = "web.log"

_APPLESCRIPT = '''\
-- wrench notifier: posts a notification, and opens the dashboard when one is clicked.
-- Generated by wrench; rebuilt automatically when wrench changes it.
property stateDir : "__STATE__"

on handle()
	set titleFile to stateDir & "/pending.title"
	set bodyFile to stateDir & "/pending.body"
	-- only a request written in the last minute counts: a stale one must not
	-- turn a click into a second notification
	set fresh to (do shell script "find " & quoted form of titleFile & " -mmin -1 2>/dev/null | head -1")
	if fresh is not "" then
		set t to (do shell script "cat " & quoted form of titleFile)
		set b to (do shell script "cat " & quoted form of bodyFile & " 2>/dev/null || true")
		do shell script "rm -f " & quoted form of titleFile & " " & quoted form of bodyFile
		display notification b with title t
		delay 2
	else
		do shell script "rm -f " & quoted form of titleFile & " " & quoted form of bodyFile
		do shell script "__SHOW__ >/dev/null 2>&1 &"
	end if
end handle

on run
	handle()
end run

on reopen
	handle()
end reopen
'''


def notifier_dir(data_dir) -> Path:
    return Path(data_dir) / DIR_NAME


def show_command() -> str:
    """The shell command the helper runs on a click: this install's wrench,
    with the config/data dirs it was built under."""
    argv = [sys.executable, "-m", "wrench", "show", "--from-toast"]
    env = [f"{k}={os.environ[k]}" for k in ("WRENCH_CONFIG_DIR", "WRENCH_DATA_DIR")
           if os.environ.get(k)]
    return " ".join(shlex.quote(a) for a in (["/usr/bin/env"] + env if env else []) + argv)


def applet_source(data_dir) -> str:
    def as_string(s: str) -> str:            # inside an AppleScript string literal
        return s.replace("\\", "\\\\").replace('"', '\\"')
    return (_APPLESCRIPT
            .replace("__STATE__", as_string(str(notifier_dir(data_dir))))
            .replace("__SHOW__", as_string(show_command())))


def _run(argv: list[str], timeout: float = 60):
    return subprocess.run(argv, check=False, capture_output=True, text=True,  # noqa: S603
                          timeout=timeout)


def ensure_applet(data_dir, runner=None) -> Path | None:
    """Build the helper app if it is missing or out of date. None when this
    machine cannot build one (not macOS, no osacompile, build failed)."""
    if platform.system() != "Darwin" or not shutil.which("osacompile"):
        return None
    run = runner or _run
    ndir = notifier_dir(data_dir)
    app = ndir / APP_NAME
    src = applet_source(data_dir)
    stamp = hashlib.sha256(src.encode("utf-8")).hexdigest()
    stamp_file = ndir / "applet.stamp"
    try:
        if app.is_dir() and stamp_file.read_text(encoding="utf-8").strip() == stamp:
            return app
    except OSError:
        pass
    try:
        ndir.mkdir(parents=True, exist_ok=True)
        src_file = ndir / "notifier.applescript"
        src_file.write_text(src, encoding="utf-8")
        if app.exists():
            shutil.rmtree(app)
        r = run(["osacompile", "-o", str(app), str(src_file)])
        if getattr(r, "returncode", 1) != 0 or not app.is_dir():
            return None
        plist = str(app / "Contents" / "Info.plist")
        for key, kind, value in (("CFBundleIdentifier", "-string", BUNDLE_ID),
                                 ("CFBundleName", "-string", "wrench"),
                                 ("CFBundleDisplayName", "-string", "wrench"),
                                 ("LSUIElement", "-bool", "true")):   # no Dock icon
            run(["plutil", "-replace", key, kind, value, plist])
        # the bundle changed after it was compiled: sign it again (ad hoc)
        if shutil.which("codesign"):
            run(["codesign", "--force", "--deep", "-s", "-", str(app)])
        stamp_file.write_text(stamp + "\n", encoding="utf-8")
        return app
    except (OSError, subprocess.SubprocessError):
        return None


def post_macos(title: str, body: str, data_dir, notif_id: str = "", runner=None) -> bool:
    """Post a clickable notification through the helper. False → the caller
    should fall back to plain osascript."""
    app = ensure_applet(data_dir, runner=runner)
    if app is None:
        return False
    run = runner or _run
    ndir = notifier_dir(data_dir)
    try:
        (ndir / "pending.body").write_text(body[:1000], encoding="utf-8")
        (ndir / "pending.title").write_text(title[:200], encoding="utf-8")   # written last
        (ndir / "last").write_text(json.dumps({"id": notif_id, "ts": time.time()}),
                                   encoding="utf-8")
        r = run(["open", "-g", str(app)])        # -g: do not steal focus
        return getattr(r, "returncode", 1) == 0
    except (OSError, subprocess.SubprocessError):
        return False


def last_clicked(data_dir) -> str:
    """The id of the notification most recently posted as a toast."""
    try:
        return str(json.loads((notifier_dir(data_dir) / "last").read_text(
            encoding="utf-8")).get("id") or "")
    except (OSError, ValueError, AttributeError):
        return ""


# ---------------------------------------------------------------- Windows
WIN_APP_ID = "wrench"
WIN_PROTOCOL = "wrench-show"


def ps_literal(text: str) -> str:
    """A PowerShell expression for ``text`` that contains no double quote —
    the script travels on a command line, where a stray ``"`` is eaten."""
    parts = str(text).replace("'", "''").split('"')
    return "(" + "+[char]34+".join(f"'{p}'" for p in parts) + ")"


def windows_show_argv() -> tuple[str, str]:
    """(program, arguments) the wrench-show: link runs. pythonw has no console
    window to flash."""
    exe = Path(sys.executable)
    pyw = exe.with_name("pythonw.exe")
    return str(pyw if pyw.is_file() else exe), "-m wrench show --from-toast"


def windows_register_script(program: str | None = None, arguments: str | None = None) -> str:
    """PowerShell that registers, for this user only (HKCU, no admin):

    * the app id ``wrench`` with a display name, so the toast is filed under
      "wrench" rather than under nothing;
    * a ``wrench-show:`` link type whose handler runs
      ``wrench show --from-toast``.

    Leaves ``$ok`` true when the link type is in place."""
    prog, args = windows_show_argv()
    prog, args = program or prog, arguments if arguments is not None else args
    command = f"([char]34+{ps_literal(prog)}+[char]34+{ps_literal(' ' + args)})"
    return (
        "$ok=$false;try{$ErrorActionPreference='Stop';"
        f"$a='HKCU:\\Software\\Classes\\AppUserModelId\\{WIN_APP_ID}';"
        "New-Item -Path $a -Force|Out-Null;"
        "Set-ItemProperty -Path $a -Name 'DisplayName' -Value 'wrench';"
        f"$p='HKCU:\\Software\\Classes\\{WIN_PROTOCOL}';"
        "$c=$p+'\\shell\\open\\command';New-Item -Path $c -Force|Out-Null;"
        f"Set-ItemProperty -Path $p -Name '(default)' -Value 'URL:{WIN_PROTOCOL}';"
        "Set-ItemProperty -Path $p -Name 'URL Protocol' -Value '';"
        f"Set-ItemProperty -Path $c -Name '(default)' -Value {command};"
        "$ok=$true}catch{};$ErrorActionPreference='Continue';"
    )


def windows_script(title: str, body: str, url: str = "", click: bool = True,
                   program: str | None = None, arguments: str | None = None) -> str:
    """The PowerShell that posts one toast on Windows.

    Left alone, a Windows toast from a script has problems of the same family
    as the macOS one: it is filed under an app id nobody registered, and
    clicking it does nothing. So the script first registers the app id and a
    ``wrench-show:`` link type (see ``windows_register_script``) and makes the
    toast open that link: a click runs ``wrench show``, which starts the
    dashboard if needed and opens the alert. If the registration fails, the
    toast opens the alert's http address directly instead.

    Every extra is wrapped: a failure there must never cost the toast. The
    script contains no double quote, because it travels on a command line.
    """
    launch = ""
    if click:
        fallback = url if url.startswith(("http://", "https://")) else ""
        launch = (
            f"$l=if($ok){{'{WIN_PROTOCOL}:open'}}else{{{ps_literal(fallback)}}};"
            "if($l){try{$t.DocumentElement.SetAttribute('activationType','protocol');"
            "$t.DocumentElement.SetAttribute('launch',$l)}catch{}};"
        )
    return (
        (windows_register_script(program, arguments) if click else "")
        + "[Windows.UI.Notifications.ToastNotificationManager,Windows.UI.Notifications,"
        "ContentType=WindowsRuntime]|Out-Null;"
        "$t=[Windows.UI.Notifications.ToastNotificationManager]::GetTemplateContent("
        "[Windows.UI.Notifications.ToastTemplateType]::ToastText02);"
        "$x=$t.GetElementsByTagName('text');"
        f"$x.Item(0).AppendChild($t.CreateTextNode({ps_literal(title)}))|Out-Null;"
        f"$x.Item(1).AppendChild($t.CreateTextNode({ps_literal(body)}))|Out-Null;"
        + launch +
        "[Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier("
        f"'{WIN_APP_ID}').Show([Windows.UI.Notifications.ToastNotification]::new($t))"
    )


# ---------------------------------------------------------------- Linux
def linux_supports_actions(runner=None) -> bool:
    """notify-send grew --action (and waiting for it) in libnotify 0.7.10+."""
    if runner is None and not shutil.which("notify-send"):
        return False
    try:
        r = runner(["notify-send", "--help"]) if runner else _run(["notify-send", "--help"], 10)
        return "--action" in (getattr(r, "stdout", "") or "")
    except (OSError, subprocess.SubprocessError):
        return False


def post_linux(title: str, body: str, notif_id: str = "") -> bool:
    """Post a toast with a "Show" action, from a detached helper process that
    waits for the click. False → the caller sends the plain toast.

    A plain ``notify-send`` toast on Linux is not broken the way the macOS one
    was — clicking it simply does nothing. With an action, clicking the toast
    (or its Show button) opens the dashboard at the alert."""
    if not linux_supports_actions():
        return False
    try:
        subprocess.Popen(  # noqa: S603
            [sys.executable, "-m", "wrench", "show", "--toast-wait",
             "--toast-title", title[:200], "--toast-body", body[:1000],
             "--toast-id", notif_id],
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            start_new_session=True, close_fds=True)
        return True
    except OSError:
        return False


def linux_wait_and_show(cfg, title: str, body: str, notif_id: str = "", runner=None,
                        timeout: float = 900) -> str:
    """Run in the detached helper: show the toast, wait, act on a click.
    Returns 'clicked' | 'dismissed' | 'failed'."""
    argv = ["notify-send", "--app-name=wrench", "--urgency=normal",
            "--action=default=Show", "--action=show=Show", title, body]
    try:
        r = (runner or (lambda a: subprocess.run(a, check=False, capture_output=True,  # noqa: S603
                                                 text=True, timeout=timeout)))(argv)
    except (OSError, subprocess.SubprocessError):
        return "failed"
    if getattr(r, "returncode", 1) != 0:
        return "failed"
    if (getattr(r, "stdout", "") or "").strip() in ("default", "show"):
        show(cfg, notif_id)
        return "clicked"
    return "dismissed"


# ---------------------------------------------------------------- wrench show
def web_target(cfg) -> dict:
    """Where this install's dashboard is (or would be) served."""
    web = (getattr(cfg, "raw", None) or {}).get("web", {})
    web = web if isinstance(web, dict) else {}
    bind = str(web.get("bind", "127.0.0.1") or "127.0.0.1")
    tls = bool(web.get("tls_cert"))
    port = int(getattr(cfg, "web_port", 8787) or 8787)
    return {"bind": bind, "port": port, "tls": tls,
            "base": f"{'https' if tls else 'http'}://localhost:{port}"}


def dashboard_url(cfg, notif_id: str = "") -> str:
    base = web_target(cfg)["base"]
    nid = "".join(c for c in str(notif_id or "") if c.isalnum())[:40]
    return f"{base}/#notification={nid}" if nid else f"{base}/#notifications"


def dashboard_running(cfg) -> bool:
    from . import fleetsetup
    t = web_target(cfg)
    return fleetsetup.hub_answers(t["bind"], t["port"], t["tls"])


def start_dashboard(cfg, wait_s: float = 12.0, argv: list[str] | None = None) -> dict:
    """Start `wrench web` in the background. {ok, pid, detail}."""
    if dashboard_running(cfg):
        return {"ok": True, "started": False, "detail": "already running"}
    data_dir = Path(cfg.data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    log = data_dir / WEB_LOG
    cmd = argv or [sys.executable, "-m", "wrench", "web"]
    kwargs: dict = {}
    if os.name == "nt":
        kwargs["creationflags"] = (getattr(subprocess, "DETACHED_PROCESS", 0)
                                   | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0))
    else:
        kwargs["start_new_session"] = True
    try:
        with open(log, "ab") as out:
            proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=out,  # noqa: S603
                                    stderr=subprocess.STDOUT, close_fds=True, **kwargs)
    except OSError as e:
        return {"ok": False, "started": False, "detail": f"could not start the dashboard: {e}"}
    (data_dir / WEB_PID).write_text(f"{proc.pid}\n", encoding="utf-8")
    deadline = time.time() + wait_s
    while time.time() < deadline:
        if dashboard_running(cfg):
            return {"ok": True, "started": True, "pid": proc.pid, "detail": f"started (pid {proc.pid})"}
        if proc.poll() is not None:
            break
        time.sleep(0.3)
    tail = ""
    try:
        tail = log.read_text(encoding="utf-8", errors="replace")[-300:].strip()
    except OSError:
        pass
    return {"ok": False, "started": False,
            "detail": "the dashboard did not come up" + (f" — {tail}" if tail else "")}


def stop_dashboard(cfg) -> dict:
    """Stop a dashboard that `wrench show` (or `wrench web --detach`) started."""
    from . import fleetsetup
    data_dir = Path(cfg.data_dir)
    try:
        pid = int((data_dir / WEB_PID).read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        pid = 0
    if not pid or not fleetsetup._pid_alive(pid):  # noqa: SLF001
        try:
            (data_dir / WEB_PID).unlink()
        except OSError:
            pass
        return {"ok": False, "detail": "no dashboard started in the background is running"}
    if os.name != "nt":
        try:
            cmd = subprocess.run(["ps", "-p", str(pid), "-o", "command="],  # noqa: S603,S607
                                 capture_output=True, text=True, timeout=10).stdout
        except (OSError, subprocess.SubprocessError):
            cmd = ""
        if "wrench" not in cmd or " web" not in cmd:
            return {"ok": False, "detail": f"pid {pid} is no longer a wrench dashboard — "
                                           "not touching it"}
    try:
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"],  # noqa: S603,S607
                           capture_output=True, timeout=20)
        else:
            import signal
            os.kill(pid, signal.SIGTERM)
    except OSError as e:
        return {"ok": False, "detail": f"could not stop pid {pid}: {e}"}
    for _ in range(25):
        if not fleetsetup._pid_alive(pid):  # noqa: SLF001
            break
        time.sleep(0.2)
    try:
        (data_dir / WEB_PID).unlink()
    except OSError:
        pass
    return {"ok": True, "detail": f"stopped the dashboard (pid {pid})"}


def show(cfg, notif_id: str = "", open_browser: bool = True, opener=None,
         start: bool = True) -> dict:
    """Open the dashboard at a notification, starting it if need be."""
    url = dashboard_url(cfg, notif_id)
    started = False
    if not dashboard_running(cfg):
        if not start:
            return {"ok": False, "url": url, "started": False,
                    "detail": "the dashboard is not running — start it with `wrench web`"}
        res = start_dashboard(cfg)
        if not res["ok"]:
            return {"ok": False, "url": url, "started": False, "detail": res["detail"]}
        started = bool(res.get("started"))
    if open_browser:
        try:
            if opener is None:
                import webbrowser
                opener = webbrowser.open
            opener(url)
        except Exception as e:  # noqa: BLE001
            return {"ok": False, "url": url, "started": started,
                    "detail": f"could not open a browser: {e}"}
    return {"ok": True, "url": url, "started": started,
            "detail": "opened" if open_browser else "ready"}
